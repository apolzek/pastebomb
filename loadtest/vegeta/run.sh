#!/usr/bin/env bash
#
# Vegeta driver for pastebomb.
#
# Vegeta is a constant-rate attacker: you tell it a request rate and it holds
# it regardless of how the service responds. That makes it the right tool for
# answering "what does latency look like at exactly N requests per second?",
# which neither k6's VU model nor Locust's think-time model answers directly.
#
# Targets are generated rather than committed because a paste handle is random
# and only exists after seeding.
#
# Usage:
#   ./loadtest/vegeta/run.sh <scenario> [rate] [duration]
#
# Scenarios: read, raw, index, write, profile, mixed, all
# Defaults:  rate=200/s, duration=30s
#
#   ./loadtest/vegeta/run.sh read 500 1m
#   ./loadtest/vegeta/run.sh all

set -euo pipefail

SCENARIO="${1:-mixed}"
RATE="${2:-200}"
DURATION="${3:-30s}"

LOADTEST_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SEED_FILE="$LOADTEST_DIR/.seed.env"
RESULTS_DIR="$LOADTEST_DIR/results"
WORK_DIR="$(mktemp -d)"
trap 'rm -rf "$WORK_DIR"' EXIT

[ -f "$SEED_FILE" ] || { echo "missing $SEED_FILE, run ./loadtest/seed.sh first" >&2; exit 1; }
# shellcheck disable=SC1090
source "$SEED_FILE"

command -v vegeta >/dev/null 2>&1 || {
    echo "vegeta is not installed. Install it with:" >&2
    echo "  go install github.com/tsenart/vegeta/v12@latest" >&2
    exit 1
}

mkdir -p "$RESULTS_DIR"
IFS=',' read -r -a SLUG_LIST <<< "$SLUGS"

# ---------------------------------------------------------------------------
# Target generation
# ---------------------------------------------------------------------------

write_body() {
    # $1 destination, $2 title
    cat > "$1" <<JSON
{"title":"$2","content":"generated by vegeta for load testing","category":"loadtest"}
JSON
}

targets_read() {
    for slug in "${SLUG_LIST[@]}"; do
        echo "GET $BASE_URL/u/anonymous/$slug"
        echo
    done
}

targets_raw() {
    for slug in "${SLUG_LIST[@]}"; do
        echo "GET $BASE_URL/u/anonymous/$slug/raw"
        echo
    done
}

targets_index() {
    for page in 1 2 3; do
        echo "GET $BASE_URL/u/anonymous/posts?page=$page&per_page=20"
        echo
    done
}

targets_write() {
    local body="$WORK_DIR/anonymous-paste.json"
    write_body "$body" "vegeta anonymous paste"
    echo "POST $BASE_URL/u/anonymous/post"
    echo "Content-Type: application/json"
    echo "@$body"
    echo
}

targets_profile() {
    echo "GET $BASE_URL/u/me"
    echo "Authorization: Bearer $TOKEN"
    echo
    echo "GET $BASE_URL/u/me/posts"
    echo "Authorization: Bearer $TOKEN"
    echo
}

# mixed weights the target list itself: vegeta cycles through targets in order,
# so repeating an entry is how a traffic mix is expressed.
targets_mixed() {
    for _ in 1 2 3 4 5 6; do targets_read; done
    for _ in 1 2 3; do targets_raw; done
    targets_index
    targets_write
    targets_profile
}

# ---------------------------------------------------------------------------
# Attack
# ---------------------------------------------------------------------------

attack() {
    local name="$1"
    local targets_file="$WORK_DIR/$name.targets"
    local results_file="$RESULTS_DIR/$name.bin"

    "targets_$name" > "$targets_file"

    echo
    echo "=============================================================="
    echo " scenario: $name   rate: ${RATE}/s   duration: $DURATION"
    echo "=============================================================="

    vegeta attack \
        -targets="$targets_file" \
        -rate="$RATE" \
        -duration="$DURATION" \
        -timeout=10s \
        -keepalive=true \
        > "$results_file"

    vegeta report "$results_file"

    # A histogram exposes the shape of the tail, which the percentile summary
    # alone hides.
    echo
    echo "latency histogram:"
    vegeta report -type='hist[0,5ms,10ms,25ms,50ms,100ms,250ms,500ms,1s]' "$results_file"

    vegeta report -type=json "$results_file" > "$RESULTS_DIR/$name.json"
    if vegeta plot "$results_file" > "$RESULTS_DIR/$name.html" 2>/dev/null; then
        echo "plot written to loadtest/results/$name.html"
    fi
}

case "$SCENARIO" in
    read|raw|index|write|profile|mixed) attack "$SCENARIO" ;;
    all)
        for name in read raw index write profile mixed; do
            attack "$name"
        done
        ;;
    *)
        echo "unknown scenario: $SCENARIO (want read, raw, index, write, profile, mixed or all)" >&2
        exit 1
        ;;
esac

echo
echo "raw results kept in loadtest/results/ for: vegeta report, vegeta plot"
