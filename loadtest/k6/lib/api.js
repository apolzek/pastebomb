// Shared helpers for the k6 scenarios: configuration, a typed client for each
// endpoint, and the custom metrics every script reports on.
import http from 'k6/http';
import { check } from 'k6';
import { Counter, Rate, Trend } from 'k6/metrics';

// Rate limiting is expected behaviour, not a failure, so it gets its own
// metric instead of inflating the error rate.
export const rateLimited = new Counter('rate_limited');
export const businessErrors = new Rate('business_errors');
export const readLatency = new Trend('read_latency', true);
export const writeLatency = new Trend('write_latency', true);

export const config = {
  baseUrl: __ENV.BASE_URL || 'http://localhost:8000',
  token: __ENV.TOKEN || '',
  slugs: (__ENV.SLUGS || '').split(',').filter(Boolean),
  secretSlug: __ENV.SECRET_SLUG || '',
  secret: __ENV.SECRET || '',
};

if (config.slugs.length === 0) {
  throw new Error('SLUGS is empty: run ./loadtest/seed.sh first and export the values from loadtest/.seed.env');
}

const jsonHeaders = { 'Content-Type': 'application/json' };

// params builds the per-request options. Declaring the acceptable statuses
// here is what keeps k6's built-in http_req_failed metric meaningful: a 401 on
// a deliberately unauthorized read, or a 429 from the rate limiter, is the
// service behaving correctly and must not be counted as a failed request.
function params(endpoint, expected, headers) {
  return {
    headers,
    tags: { endpoint },
    responseCallback: http.expectedStatuses(...expected, 429),
  };
}

export function authHeaders() {
  return { ...jsonHeaders, Authorization: `Bearer ${config.token}` };
}

// randomSlug picks one of the seeded handles. Reads spread across handles so
// the run does not simply measure one hot row in the buffer pool.
export function randomSlug() {
  return config.slugs[Math.floor(Math.random() * config.slugs.length)];
}

// track records a response against the shared metrics. `expected` lists the
// status codes that mean the endpoint behaved correctly.
export function track(response, name, expected, latency) {
  if (response.status === 429) {
    rateLimited.add(1, { endpoint: name });
    // A throttled request is a valid outcome, so it is neither an error nor a
    // latency sample worth keeping.
    return false;
  }

  const ok = expected.includes(response.status);
  businessErrors.add(!ok, { endpoint: name });
  check(response, { [`${name} returned ${expected.join(' or ')}`]: () => ok });

  if (ok && latency) {
    latency.add(response.timings.duration, { endpoint: name });
  }
  return ok;
}

export const api = {
  health() {
    const response = http.get(`${config.baseUrl}/health`, params('health', [200]));
    return track(response, 'health', [200], readLatency);
  },

  ready() {
    const response = http.get(`${config.baseUrl}/ready`, params('ready', [200]));
    return track(response, 'ready', [200], readLatency);
  },

  publicIndex(page = 1, perPage = 20) {
    const response = http.get(
      `${config.baseUrl}/u/anonymous/posts?page=${page}&per_page=${perPage}`,
      params('public_index', [200]),
    );
    return track(response, 'public_index', [200], readLatency);
  },

  readPaste(slug = randomSlug()) {
    const response = http.get(`${config.baseUrl}/u/anonymous/${slug}`, params('read_paste', [200]));
    return track(response, 'read_paste', [200], readLatency);
  },

  readRaw(slug = randomSlug()) {
    const response = http.get(`${config.baseUrl}/u/anonymous/${slug}/raw`, params('read_raw', [200]));
    return track(response, 'read_raw', [200], readLatency);
  },

  // The protected paste is read without the secret on purpose: 401 is the
  // correct answer, and it exercises the bcrypt comparison path.
  readProtectedWithoutSecret() {
    const response = http.get(
      `${config.baseUrl}/u/anonymous/${config.secretSlug}`,
      params('read_protected_denied', [401]),
    );
    return track(response, 'read_protected_denied', [401], readLatency);
  },

  readProtectedWithSecret() {
    const response = http.get(
      `${config.baseUrl}/u/anonymous/${config.secretSlug}`,
      params('read_protected_allowed', [200], { 'X-Post-Secret': config.secret }),
    );
    return track(response, 'read_protected_allowed', [200], readLatency);
  },

  publicProfile(handle) {
    const response = http.get(`${config.baseUrl}/u/${handle}`, params('public_profile', [200]));
    return track(response, 'public_profile', [200], readLatency);
  },

  createAnonymousPaste() {
    const body = JSON.stringify({
      title: `k6 paste ${__VU}-${__ITER}`,
      content: `generated by k6, virtual user ${__VU}, iteration ${__ITER}`,
      category: 'loadtest',
    });
    const response = http.post(
      `${config.baseUrl}/u/anonymous/post`,
      body,
      params('create_anonymous', [201], jsonHeaders),
    );
    return track(response, 'create_anonymous', [201], writeLatency);
  },

  createOwnedPaste() {
    const body = JSON.stringify({
      title: `k6 owned paste ${__VU}-${__ITER}`,
      content: `owned body from virtual user ${__VU}`,
      is_public: false,
    });
    const response = http.post(
      `${config.baseUrl}/u/me/post`,
      body,
      params('create_owned', [201], authHeaders()),
    );
    return track(response, 'create_owned', [201], writeLatency);
  },

  profile() {
    const response = http.get(`${config.baseUrl}/u/me`, params('profile', [200], authHeaders()));
    return track(response, 'profile', [200], readLatency);
  },

  myPastes() {
    const response = http.get(`${config.baseUrl}/u/me/posts`, params('my_pastes', [200], authHeaders()));
    return track(response, 'my_pastes', [200], readLatency);
  },

  // Login is the most expensive endpoint by design: it runs bcrypt at the
  // configured cost, so it deserves its own latency picture.
  login(email, password) {
    const body = JSON.stringify({ email, password });
    const response = http.post(`${config.baseUrl}/login`, body, params('login', [200], jsonHeaders));
    return track(response, 'login', [200], writeLatency);
  },
};
