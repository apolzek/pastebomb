#!/usr/bin/env bash
#
# Seeds the data every load test needs and writes it to loadtest/.seed.env:
# one account, its bearer token, and a handful of readable paste handles.
#
# Seeding is a separate step because the tools should spend their run
# generating load, not registering users, and because a paste handle is random
# so it cannot be hardcoded in a target file.
#
# Usage: ./loadtest/seed.sh [BASE_URL]

set -euo pipefail

BASE_URL="${1:-${BASE_URL:-http://localhost:8000}}"
PASTE_COUNT="${PASTE_COUNT:-10}"
SEED_FILE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/.seed.env"

# A unique suffix keeps repeated runs from colliding on the unique indexes.
SUFFIX="$(date +%s)$RANDOM"
USERNAME="loadtest${SUFFIX}"
EMAIL="loadtest${SUFFIX}@example.com"
PASSWORD="loadtest-password-long-enough"

fail() { echo "seed: $*" >&2; exit 1; }

json_field() {
    python3 -c 'import json,sys
data = json.load(sys.stdin)
for key in sys.argv[1].split("."):
    data = data[key]
print(data)' "$1"
}

echo "seed: waiting for $BASE_URL to become ready"
for attempt in $(seq 1 60); do
    if curl -fsS "$BASE_URL/ready" >/dev/null 2>&1; then
        break
    fi
    [ "$attempt" -eq 60 ] && fail "$BASE_URL never became ready"
    sleep 1
done

echo "seed: registering $USERNAME"
register_body=$(curl -fsS -X POST "$BASE_URL/u" \
    -H 'Content-Type: application/json' \
    -d "{\"name\":\"Load Test\",\"username\":\"$USERNAME\",\"email\":\"$EMAIL\",\"born_date\":\"1990-01-01\",\"password\":\"$PASSWORD\"}") \
    || fail "registration failed, is the rate limit override applied?"
user_id=$(printf '%s' "$register_body" | json_field data.id)

echo "seed: logging in"
token=$(curl -fsS -X POST "$BASE_URL/login" \
    -H 'Content-Type: application/json' \
    -d "{\"email\":\"$EMAIL\",\"password\":\"$PASSWORD\"}" | json_field data.token) \
    || fail "login failed"

echo "seed: creating $PASTE_COUNT public pastes"
slugs=()
for index in $(seq 1 "$PASTE_COUNT"); do
    slug=$(curl -fsS -X POST "$BASE_URL/u/anonymous/post" \
        -H 'Content-Type: application/json' \
        -d "{\"title\":\"load test paste $index\",\"content\":\"seeded body for load testing, iteration $index\",\"category\":\"loadtest\"}" \
        | json_field data.url_id) || fail "paste creation failed on iteration $index"
    slugs+=("$slug")
done

# One secret-protected paste, so the tools can exercise the 401 path too.
secret_slug=$(curl -fsS -X POST "$BASE_URL/u/anonymous/post" \
    -H 'Content-Type: application/json' \
    -d '{"title":"locked load test paste","content":"protected body","secret_access":"load-test-secret"}' \
    | json_field data.url_id) || fail "protected paste creation failed"

{
    echo "# Generated by loadtest/seed.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not commit."
    echo "BASE_URL=$BASE_URL"
    echo "USER_ID=$user_id"
    echo "USERNAME=$USERNAME"
    echo "EMAIL=$EMAIL"
    echo "PASSWORD=$PASSWORD"
    echo "TOKEN=$token"
    echo "SLUGS=$(IFS=,; echo "${slugs[*]}")"
    echo "SECRET_SLUG=$secret_slug"
    echo "SECRET=load-test-secret"
} > "$SEED_FILE"

echo "seed: wrote $SEED_FILE"
echo "seed: ${#slugs[@]} readable handles, 1 protected handle, token for $EMAIL"
